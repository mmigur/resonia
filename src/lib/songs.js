// Мелодия: народная «Калинка» (И. Ларионов, 1860, общественное достояние).
// Ноты сверены с открытой нотной записью (ABC, folktunefinder.com/tunes/7767):
//   фраза 1:  B A F# G A F# G A G F# E          (11 нот, тоника E)
//   фраза 2:  B B A G F# G A F# G A G F# E      (13 нот)
// semi = расстояние от тоники в полутонах, beats = длительность в долях.
//
// Слова ниже АВТОРСКИЕ: они написаны под ритм и ударения этой мелодии.
// Оригинальный текст песни здесь не воспроизводится. Хочешь свои слова —
// замени значения syl (одна нота = один слог, количество слогов должно совпадать).
const n = (semi, beats, syl) => ({ semi, beats, syl })

// «Ря-би-на, ря-би-на, ря-би-на мо-я» (ударения: би · би · би · я)
export const RYABINA_A = [
  n(7, 1, 'ря'), n(5, 1, 'би'), n(2, 0.5, 'на'),
  n(3, 0.5, 'ря'), n(5, 1, 'би'), n(2, 0.5, 'на'),
  n(3, 0.5, 'ря'), n(5, 1, 'би'), n(3, 0.5, 'на'),
  n(2, 0.5, 'мо'), n(0, 2, 'я'),
]

// Первая половина фразы (6 нот)
export const RYABINA_HALF = [
  n(7, 1, 'ря'), n(5, 1, 'би'), n(2, 0.5, 'на'),
  n(3, 0.5, 'ря'), n(5, 1, 'би'), n(2, 2, 'на'),
]

// «Под окном у нас рябина, рябина моя» (ударения: ном · би · би · я).
// Ритм слегка упрощён: пунктир заменён ровными восьмыми.
export const RYABINA_B = [
  n(7, 0.5, 'под'), n(7, 0.5, 'ок'), n(5, 0.5, 'ном'),
  n(3, 0.5, 'у'), n(2, 0.5, 'нас'), n(3, 0.5, 'ря'),
  n(5, 1, 'би'), n(2, 0.5, 'на'), n(3, 0.5, 'ря'),
  n(5, 1, 'би'), n(3, 0.5, 'на'), n(2, 0.5, 'мо'), n(0, 2, 'я'),
]

// Обе фразы подряд
export const RYABINA_FULL = [...RYABINA_A.slice(0, -1), n(0, 1, 'я'), ...RYABINA_B]

// Медленный финал: первая фраза с долгой последней нотой
export const RYABINA_SLOW = [...RYABINA_A.slice(0, -1), n(0, 4, 'я')]
